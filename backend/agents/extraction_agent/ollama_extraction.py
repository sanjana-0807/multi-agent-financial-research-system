"""
Generic hybrid financial extraction.

Ollama may classify row labels, but it is NEVER trusted to invent
or return financial numbers. Python extracts numbers from actual
financial rows.
"""

import json
import re
from typing import Any, Dict, Optional

import ollama


MODEL = "llama3.2:latest"


def _extract_json(text: str) -> Optional[Dict[str, Any]]:
    if not text:
        return None

    text = text.strip()
    text = re.sub(r"^```json\s*", "", text, flags=re.IGNORECASE)
    text = re.sub(r"^```\s*", "", text)
    text = re.sub(r"\s*```$", "", text)

    try:
        result = json.loads(text)
        return result if isinstance(result, dict) else None
    except json.JSONDecodeError:
        pass

    match = re.search(r"\{.*\}", text, re.DOTALL)
    if match:
        try:
            result = json.loads(match.group(0))
            return result if isinstance(result, dict) else None
        except json.JSONDecodeError:
            pass

    return None


NUMBER_PATTERN = re.compile(
    r"""
    \(?\s*
    -?
    (?:
        \d{1,3}(?:,\d{3})+
        |
        \d+
    )
    (?:\.\d+)?
    \s*
    \)?
    """,
    re.VERBOSE,
)


def _parse_number(raw: str) -> Optional[float]:
    if not raw:
        return None

    value = raw.strip()
    negative = value.startswith("(") or value.startswith("-")

    value = (
        value.replace(",", "")
        .replace("(", "")
        .replace(")", "")
        .strip()
    )

    try:
        number = float(value)
    except ValueError:
        return None

    # Never interpret a year as a metric.
    if 1900 <= number <= 2100:
        return None

    return -number if negative else number


def _normalize(text: str) -> str:
    if not text:
        return ""

    text = text.replace("\u00a0", " ")
    text = text.replace("\u200b", "")
    text = re.sub(r"[ \t]+", " ", text)
    return text


