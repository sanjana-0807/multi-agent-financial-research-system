def _values_immediately_after(
    text: str,
    position: int,
    max_chars: int = 100,
) -> list[float]:
    """
    Extract consecutive financial values immediately following
    a financial statement row label.

    Designed for rows such as:

        Total assets 624,894 818,042

        Net income 30,425 59,248 77,670

    The parser stops when it encounters substantial prose.
    """

    candidate = text[
        position:position + max_chars
    ]

    candidate = candidate.lstrip(
        " \t|-–—"
    )

    # Remove an optional currency symbol.
    candidate = re.sub(
        r"^(?:\$|₹|Rs\.?)\s*",
        "",
        candidate,
        flags=re.IGNORECASE,
    )

    values = []

    cursor = 0

    while cursor < len(candidate):

        # Skip ordinary whitespace.
        while (
            cursor < len(candidate)
            and candidate[cursor].isspace()
        ):
            cursor += 1

        # Optional currency symbol before each value.
        currency = re.match(
            r"(?:\$|₹|Rs\.?)\s*",
            candidate[cursor:],
            re.IGNORECASE,
        )

        if currency:
            cursor += currency.end()

        match = re.match(
            r"\(?-?(?:\d{1,3}(?:,\d{3})+|\d+)"
            r"(?:\.\d+)?\)?",
            candidate[cursor:],
        )

        if not match:
            break

        value = _parse_number(
            match.group(0)
        )

        if value is None:
            break

        values.append(value)

        cursor += match.end()

        if len(values) >= 3:
            break

        # Look ahead at the text between this value and
        # the next possible value.
        remaining = candidate[cursor:]

        next_number = re.search(
            r"\(?-?(?:\d{1,3}(?:,\d{3})+|\d+)"
            r"(?:\.\d+)?\)?",
            remaining,
        )

        if not next_number:
            break

        separator = remaining[
            :next_number.start()
        ]

        # If substantial alphabetic prose appears before
        # the next number, this is no longer the same row.
        letters = re.sub(
            r"[\s:;,\-–—|$₹.]",
            "",
            separator,
        )

        if len(letters) > 3:
            break

        cursor += next_number.start()

    return values


def _find_row_values(
    section: str,
    terms: list[str],
    max_chars: int = 100,
) -> Optional[list[float]]:
    section = _normalize(section)
    candidates = []

    for term in terms:
        pattern = re.compile(
            re.escape(term).replace(r"\ ", r"\s*"),
            re.IGNORECASE,
        )

        for match in pattern.finditer(section):
            values = _values_immediately_after(
                section,
                match.end(),
                max_chars,
            )

            if not values:
                continue

            # Prefer more specific labels and earlier table rows.
            specificity = len(term.split())
            score = specificity * 10

            candidates.append(
                (score, match.start(), values)
            )

    if not candidates:
        return None

    candidates.sort(
        key=lambda item: (item[0], -item[1]),
        reverse=True,
    )

    return candidates[0][2]


